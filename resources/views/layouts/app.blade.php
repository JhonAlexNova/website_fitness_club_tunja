    $(document).ready(function() {

        // Add click event handler to toggle submenus
        $('.has-submenu').click(function(e) {
            e.preventDefault(); // Prevent the default link behavior
          //  $(this).find('ul').toggle(); // Toggle the submenu
        });


    // Cerrar otros menús cuando se abre uno nuevo
    $('.nav-link').on('click', function(e) {
        if ($(this).hasClass('collapsed') || $(this).parent().hasClass('menu-open')) {
            // Si es un menú desplegable
            var parentLi = $(this).parent();
            var parentUl = parentLi.parent();
            
            // Cerrar todos los menús excepto el actual
            $('.nav-item.menu-open').not(parentLi).removeClass('menu-open').children('.nav-treeview').slideUp();
            
            // Alternar el estado del menú actual
            parentLi.toggleClass('menu-open');
            parentLi.children('.nav-treeview').slideToggle();
            
            // Prevenir el comportamiento predeterminado solo para enlaces que son padres de menús
            if ($(this).attr('href') === '#') {
                e.preventDefault();
            }
        }
    });
    
    // Cerrar menú al hacer clic en un ítem principal activo
    $('.nav-link.active').on('click', function() {
        if ($(this).parent().hasClass('menu-open')) {
            $(this).parent().removeClass('menu-open');
            $(this).next('.nav-treeview').slideUp();
        }
    });
});
    

    
